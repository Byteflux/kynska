// Builds agent-ready docs from Strudel's docs site at the pinned version:
// out/docs/<page>.md, out/docs/reference.md, out/llms.txt and out/llms-full.txt.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { OUT_DIR } from '../paths.ts';
import { buildReference, fetchStrudel } from '../reference/build.ts';
import { formatEntry, ReferenceIndex } from '../reference/lookup.ts';
import { readPin } from '../reference/pin.ts';
import { convertPage, SITE } from './convert.ts';
import { readSidebar } from './sidebar.ts';

/** Sidebar pages left out: the community showcase, and the blog (not an MDX page). */
const EXCLUDED = new Set(['intro/showcase', 'blog']);

export type DocsPage = { slug: string; title: string; summary: string; section: string; file: string; chars: number };

export type DocsResult = {
  version: string;
  commit: string;
  pages: DocsPage[];
  files: { llms: string; llmsFull: string; reference: string };
  sizes: { llmsFull: number; reference: number };
  warnings: string[];
};

async function mdxPages(pagesDir: string, dir = ''): Promise<string[]> {
  const slugs: string[] = [];
  for (const entry of await readdir(join(pagesDir, dir), { withFileTypes: true })) {
    const path = dir ? `${dir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) slugs.push(...(await mdxPages(pagesDir, path)));
    else if (entry.name.endsWith('.mdx')) slugs.push(path.replace(/\.mdx$/, ''));
  }
  return slugs;
}

export async function buildDocs(outDir = OUT_DIR): Promise<DocsResult> {
  const pin = await readPin();
  const reference = await buildReference(join(outDir, 'reference.json'));
  const index = new ReferenceIndex(reference);
  const source = await fetchStrudel(pin);
  const website = join(source, 'website', 'src');
  const pagesDir = join(website, 'pages');
  const sidebar = readSidebar(await readFile(join(website, 'config.ts'), 'utf8'), 'en');
  const available = new Set((await mdxPages(pagesDir)).filter((s) => !s.startsWith('de/')));
  const warnings: string[] = [];

  // Pages in sidebar order, then English pages the sidebar does not list.
  const plan: { slug: string; section: string; text?: string }[] = [];
  const seen = new Set<string>();
  for (const section of sidebar) {
    for (const { link, text } of section.links) {
      if (EXCLUDED.has(link) || seen.has(link)) continue;
      if (!available.has(link)) {
        if (!link.startsWith('de/')) warnings.push(`sidebar links to "${link}", which is not an MDX page`);
        continue;
      }
      seen.add(link);
      plan.push({ slug: link, section: section.title, text });
    }
  }
  for (const slug of [...available].sort()) {
    if (!seen.has(slug) && !EXCLUDED.has(slug)) plan.push({ slug, section: 'More pages' });
  }

  const docsDir = join(outDir, 'docs');
  await rm(docsDir, { recursive: true, force: true });
  const slugs = new Set(plan.map((p) => p.slug));
  const pages: DocsPage[] = [];
  const full: string[] = [];
  const footer = (slug: string) => `\n---\n\nFrom ${SITE}/${slug}/ (Strudel ${pin.version}, generated by Kynska).\n`;
  for (const { slug, section, text } of plan) {
    let converted: ReturnType<typeof convertPage>;
    try {
      converted = convertPage(await readFile(join(pagesDir, `${slug}.mdx`), 'utf8'), { slug, reference: index, pages: slugs });
    } catch (error) {
      const e = error as Error & { line?: number; column?: number };
      warnings.push(`${slug}: could not convert (${e.message}${e.line ? ` at ${e.line}:${e.column}` : ''}), page left out`);
      continue;
    }
    for (const w of converted.warnings) warnings.push(`${slug}: ${w}`);
    const file = join(docsDir, `${slug}.md`);
    const markdown = `${converted.markdown.trimEnd()}\n${footer(slug)}`;
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, markdown);
    // The sidebar's wording ("What is Strudel?") is what readers of the site see.
    pages.push({ slug, title: text ?? converted.title, summary: converted.summary, section, file, chars: markdown.length });
    full.push(markdown);
  }

  // Every function, grouped as the source groups them.
  const referenceFile = join(docsDir, 'reference.md');
  const referenceText = [
    '# Strudel function reference',
    '',
    `Every documented function in Strudel ${pin.version}, alphabetically. Each entry shows how to call it, its parameters and examples.`,
    '',
    ...reference.functions.map((entry) => formatEntry(entry).replace(/^## /, '## ')),
  ].join('\n\n');
  await writeFile(referenceFile, `${referenceText}\n`);

  const intro = [
    '# Strudel',
    '',
    `> Strudel is a live coding environment for making music in the browser: patterns written in JavaScript with the TidalCycles pattern language, played at ${SITE}. These docs are Strudel ${pin.version}'s own documentation (commit ${pin.commit.slice(0, 7)}), converted to Markdown by Kynska.`,
    '',
    'Code blocks are complete examples that run on strudel.cc. Lines starting with `$:` play together. The function reference lists every documented function with its parameters and examples.',
  ];
  const link = (p: DocsPage) => `- [${p.title}](${relative(outDir, p.file)})${p.summary ? `: ${p.summary}` : ''}`;
  const sections = [...new Set(pages.map((p) => p.section))].filter((s) => s !== 'More pages');
  const llms = [
    ...intro,
    ...sections.flatMap((s) => ['', `## ${s}`, '', ...pages.filter((p) => p.section === s).map(link)]),
    '',
    '## Reference',
    '',
    `- [Function reference](${relative(outDir, referenceFile)}): every documented function (${reference.functions.length}), with how to call it, parameters and examples.`,
    '',
    '## Optional',
    '',
    ...pages.filter((p) => p.section === 'More pages').map(link),
  ].join('\n');
  const llmsFile = join(outDir, 'llms.txt');
  await writeFile(llmsFile, `${llms}\n`);
  const llmsFullFile = join(outDir, 'llms-full.txt');
  const llmsFull = `${intro.join('\n')}\n\n${full.join('\n')}`;
  await writeFile(llmsFullFile, llmsFull);

  return {
    version: pin.version,
    commit: pin.commit,
    pages,
    files: { llms: llmsFile, llmsFull: llmsFullFile, reference: referenceFile },
    sizes: { llmsFull: llmsFull.length, reference: referenceText.length },
    warnings,
  };
}

const kb = (chars: number) => `${Math.round(chars / 1024)} KB, about ${Math.round(chars / 4 / 1000)}k tokens`;

export function formatDocsResult(result: DocsResult): string {
  const rel = (p: string) => relative(process.cwd(), p) || p;
  const lines = [
    `Built docs from Strudel ${result.version} (${result.commit.slice(0, 7)}):`,
    `  ${rel(result.files.llms)}: index of ${result.pages.length} pages`,
    `  ${rel(result.files.llmsFull)}: every page (${kb(result.sizes.llmsFull)})`,
    `  ${rel(dirname(result.files.reference))}/: one Markdown file per page, and reference.md (${kb(result.sizes.reference)})`,
  ];
  if (result.warnings.length) lines.push(`${result.warnings.length} warning${result.warnings.length === 1 ? '' : 's'}:`, ...result.warnings.map((w) => `  ${w}`));
  return lines.join('\n');
}
